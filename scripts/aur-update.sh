#!/usr/bin/env bash
# Write the deskvncviewer-bin PKGBUILD and .SRCINFO for one release.
#
#   scripts/aur-update.sh 0.36.1            # writes packaging/aur/deskvncviewer-bin/
#   scripts/aur-update.sh v0.37.0 /tmp/out  # or into another directory
#
# The checksums of the two .deb files come from SHA256SUMS.txt on the GitHub
# release, the same file people verify their downloads against. The license
# files are hashed from the tagged source. Needs bash, curl and sha256sum (or
# shasum on macOS). Nothing here talks to the AUR.
set -euo pipefail

repo=psmux/DeskVNC
pkgname=deskvncviewer-bin
pkgrel=${PKGREL:-1}

if [ $# -lt 1 ]; then
  echo "usage: $0 <version> [output dir]" >&2
  exit 2
fi
pkgver=${1#v}
here=$(cd "$(dirname "$0")/.." && pwd)
out=${2:-$here/packaging/aur/$pkgname}

if ! [[ $pkgver =~ ^[0-9]+(\.[0-9]+)*$ ]]; then
  echo "version '$pkgver' is not a plain dotted number; pacman would reject it" >&2
  exit 2
fi

if command -v sha256sum >/dev/null; then
  sha() { sha256sum | cut -d' ' -f1; }
else
  sha() { shasum -a 256 | cut -d' ' -f1; }
fi

release=https://github.com/$repo/releases/download/v$pkgver
raw=https://raw.githubusercontent.com/$repo/v$pkgver

sums=$(curl -fsSL "$release/SHA256SUMS.txt")
pick() {
  local s
  s=$(printf '%s\n' "$sums" | awk -v f="$1" '$2 == f || $2 == "*" f { print $1 }')
  if ! [[ $s =~ ^[0-9a-f]{64}$ ]]; then
    echo "no checksum for $1 in $release/SHA256SUMS.txt" >&2
    exit 1
  fi
  echo "$s"
}
sum_x86_64=$(pick "DeskVNCViewer_${pkgver}_amd64.deb")
sum_aarch64=$(pick "DeskVNCViewer_${pkgver}_arm64.deb")
sum_mit=$(curl -fsSL "$raw/LICENSE-MIT" | sha)
sum_apache=$(curl -fsSL "$raw/LICENSE-APACHE" | sha)

mkdir -p "$out"

# The runtime dependencies are the libraries the release binaries link
# against, plus the ones the app opens at run time (the tray icon library,
# X11 and XInput). namcap cannot see those three and calls them unneeded;
# keep them. The .deb control file only names webkit2gtk, gtk3 and
# appindicator; Debian pulls the rest in through those. Arch ships the
# Ayatana flavour of appindicator, which the tray code tries first.
cat > "$out/PKGBUILD" <<EOF
# Maintainer: psmux <52248669+psmux@users.noreply.github.com>
#
# Generated by scripts/aur-update.sh in https://github.com/$repo.
# Edit that script rather than this file.

pkgname=$pkgname
_pkgname=deskvncviewer
pkgver=$pkgver
pkgrel=$pkgrel
pkgdesc='VNC, RDP and SSH desktop client with a CLI (dvv) for agents to drive remote machines'
arch=('x86_64' 'aarch64')
url='https://github.com/$repo'
license=('MIT OR Apache-2.0')
depends=(
  'cairo'
  'dbus'
  'gdk-pixbuf2'
  'glib2'
  'glibc'
  'gtk3'
  'hicolor-icon-theme'
  'libayatana-appindicator'
  'libgcc'
  'libpipewire'
  'libsoup3'
  'libstdc++'
  'libx11'
  'libxi'
  'libxkbcommon'
  'webkit2gtk-4.1'
)
optdepends=(
  'gnome-keyring: keep saved passwords in the Secret Service (KWallet works too)'
)
provides=("\$_pkgname=\$pkgver")
conflicts=("\$_pkgname")
options=('!strip' '!debug')
source=(
  "LICENSE-MIT-\$pkgver::https://raw.githubusercontent.com/$repo/v\$pkgver/LICENSE-MIT"
  "LICENSE-APACHE-\$pkgver::https://raw.githubusercontent.com/$repo/v\$pkgver/LICENSE-APACHE"
)
source_x86_64=("DeskVNCViewer_\${pkgver}_amd64.deb::https://github.com/$repo/releases/download/v\$pkgver/DeskVNCViewer_\${pkgver}_amd64.deb")
source_aarch64=("DeskVNCViewer_\${pkgver}_arm64.deb::https://github.com/$repo/releases/download/v\$pkgver/DeskVNCViewer_\${pkgver}_arm64.deb")
noextract=("DeskVNCViewer_\${pkgver}_amd64.deb" "DeskVNCViewer_\${pkgver}_arm64.deb")
sha256sums=('$sum_mit'
            '$sum_apache')
sha256sums_x86_64=('$sum_x86_64')
sha256sums_aarch64=('$sum_aarch64')

package() {
  local deb
  case \$CARCH in
    x86_64) deb=DeskVNCViewer_\${pkgver}_amd64.deb ;;
    aarch64) deb=DeskVNCViewer_\${pkgver}_arm64.deb ;;
  esac

  # A .deb is an ar archive holding data.tar.*; bsdtar reads both layers.
  bsdtar -xOf "\$deb" 'data.tar.*' | bsdtar -xf - -C "\$pkgdir"

  # The viewer and the dvv CLI land in /usr/bin, the menu entry in
  # /usr/share/applications and the icons under hicolor, as on Debian.
  test -x "\$pkgdir/usr/bin/\$_pkgname"
  test -x "\$pkgdir/usr/bin/dvv"

  # The bundled entry has an empty Categories line, so menus file it under
  # Other. Give it the freedesktop category for remote desktop clients.
  sed -i 's/^Categories=\$/Categories=Network;RemoteAccess;/' \\
    "\$pkgdir/usr/share/applications/DeskVNCViewer.desktop"

  install -Dm644 "LICENSE-MIT-\$pkgver" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE-MIT"
  install -Dm644 "LICENSE-APACHE-\$pkgver" "\$pkgdir/usr/share/licenses/\$pkgname/LICENSE-APACHE"
}
EOF

# .SRCINFO is what the AUR web interface reads. makepkg --printsrcinfo writes
# it on Arch; this is the same layout, so the script also works elsewhere.
deb_url=https://github.com/$repo/releases/download/v$pkgver
cat > "$out/.SRCINFO" <<EOF
pkgbase = $pkgname
	pkgdesc = VNC, RDP and SSH desktop client with a CLI (dvv) for agents to drive remote machines
	pkgver = $pkgver
	pkgrel = $pkgrel
	url = https://github.com/$repo
	arch = x86_64
	arch = aarch64
	license = MIT OR Apache-2.0
	depends = cairo
	depends = dbus
	depends = gdk-pixbuf2
	depends = glib2
	depends = glibc
	depends = gtk3
	depends = hicolor-icon-theme
	depends = libayatana-appindicator
	depends = libgcc
	depends = libpipewire
	depends = libsoup3
	depends = libstdc++
	depends = libx11
	depends = libxi
	depends = libxkbcommon
	depends = webkit2gtk-4.1
	optdepends = gnome-keyring: keep saved passwords in the Secret Service (KWallet works too)
	provides = deskvncviewer=$pkgver
	conflicts = deskvncviewer
	noextract = DeskVNCViewer_${pkgver}_amd64.deb
	noextract = DeskVNCViewer_${pkgver}_arm64.deb
	options = !strip
	options = !debug
	source = LICENSE-MIT-$pkgver::$raw/LICENSE-MIT
	source = LICENSE-APACHE-$pkgver::$raw/LICENSE-APACHE
	sha256sums = $sum_mit
	sha256sums = $sum_apache
	source_x86_64 = DeskVNCViewer_${pkgver}_amd64.deb::$deb_url/DeskVNCViewer_${pkgver}_amd64.deb
	sha256sums_x86_64 = $sum_x86_64
	source_aarch64 = DeskVNCViewer_${pkgver}_arm64.deb::$deb_url/DeskVNCViewer_${pkgver}_arm64.deb
	sha256sums_aarch64 = $sum_aarch64

pkgname = $pkgname
EOF

# On Arch, check the hand written .SRCINFO against makepkg's own.
if command -v makepkg >/dev/null; then
  if ! diff -u "$out/.SRCINFO" <(cd "$out" && makepkg --printsrcinfo); then
    echo ".SRCINFO differs from makepkg --printsrcinfo" >&2
    exit 1
  fi
fi

echo "wrote $out/PKGBUILD and $out/.SRCINFO for $pkgver"
